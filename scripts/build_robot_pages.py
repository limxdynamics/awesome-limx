#!/usr/bin/env python3
"""Build one page per robot from the README tables.

    python scripts/build_robot_pages.py          # write robots/*.md
    python scripts/build_robot_pages.py --check  # exit 1 if a page is out of date

The README files are the source. Each robot page holds every row whose Robot
cell names that robot, grouped by the same sections, in all four languages.
Do not edit robots/*.md by hand: change the README and run this script.
"""
import argparse
import os
import re
import sys

ROBOTS = ["TRON1", "TRON2", "Oli", "Luna", "P1", "W1"]
EDITIONS = [  # (readme, suffix, language name)
    ("README.md", "", "English"),
    ("README_cn.md", "_cn", "中文"),
    ("README_ja.md", "_ja", "日本語"),
    ("README_ko.md", "_ko", "한국어"),
]
OFFICIAL = {
    "TRON1": ["tron1-robot-description", "tron1-rl-isaaclab", "tron1-mujoco-sim", "tron1-rl-deploy-python", "limxsdk-lowlevel"],
    "TRON2": ["tron2-robot-description", "tron2_rl_lab", "limxsdk-lowlevel"],
    "Oli": ["humanoid-description", "humanoid-rl-deploy-python", "limxsdk-lowlevel"],
    "Luna": ["luna-description"],
    "P1": [],
    "W1": [],
}
TEXT = {
    "": dict(
        lead="> **{n}** projects built on {r}, from the [Awesome LimX](../README.md) list.",
        official="Official {r} repositories: {links}",
        contents="Contents", back="Full list", others="Other robots",
        none="No entries yet.",
        legend="**Code** something to run · **Tutorial** something to follow · **Paper** something to read · *sim* shown only in simulation, everything else ran on a real robot",
        submit="Built something on {r}? [Submit it](https://github.com/limxdynamics/awesome-limx/issues/new?template=add-project.yml)."),
    "_cn": dict(
        lead="> 基于 {r} 的 **{n}** 个项目，摘自 [Awesome LimX](../README_cn.md) 列表。",
        official="{r} 官方仓库：{links}",
        contents="目录", back="完整列表", others="其他机型",
        none="暂无条目。",
        legend="**代码** 可以直接跑 · **教程** 可以跟着学 · **论文** 可以阅读 · *仿真* 只在仿真中展示过，其余都在实机上运行过",
        submit="用 {r} 做了东西？欢迎[提交](https://github.com/limxdynamics/awesome-limx/issues/new?template=add-project.yml)。"),
    "_ja": dict(
        lead="> {r} を使った **{n}** プロジェクト（[Awesome LimX](../README_ja.md) より）。",
        official="{r} 公式リポジトリ：{links}",
        contents="目次", back="全リスト", others="ほかの機種",
        none="まだ項目はありません。",
        legend="**コード** すぐ動かせる · **チュートリアル** 手順に沿って学べる · **論文** 読むもの · *sim* シミュレーションでのみ示された成果、それ以外は実機で動作",
        submit="{r} で何か作りましたか？[投稿はこちら](https://github.com/limxdynamics/awesome-limx/issues/new?template=add-project.yml)。"),
    "_ko": dict(
        lead="> {r}로 만든 **{n}**개 프로젝트 ([Awesome LimX](../README_ko.md) 목록에서 발췌).",
        official="{r} 공식 저장소: {links}",
        contents="목차", back="전체 목록", others="다른 기종",
        none="아직 항목이 없습니다.",
        legend="**코드** 바로 실행 가능 · **튜토리얼** 따라 배울 수 있음 · **논문** 읽을거리 · *sim* 시뮬레이션에서만 보여준 성과, 나머지는 실제 로봇에서 동작",
        submit="{r}로 무언가 만들었나요? [제출하기](https://github.com/limxdynamics/awesome-limx/issues/new?template=add-project.yml)."),
}


def slug(h):
    return re.sub(r"[^\w\- ]", "", h.lower()).replace(" ", "-")


def parse(text):
    """Yield (section, subsection, header_lines, rows) for every entry table."""
    lines = text.split("\n")
    sec = sub = None
    i = 0
    while i < len(lines):
        ln = lines[i]
        m = re.match(r"^(#{2,3}) (.*)$", ln)
        if m:
            if len(m.group(1)) == 2:
                sec, sub = m.group(2).strip(), None
            else:
                sub = m.group(2).strip()
        if ln.startswith("|") and i + 1 < len(lines) and re.match(r"^\|[\s\-:|]+\|$", lines[i + 1]):
            header = [ln, lines[i + 1]]
            j = i + 2
            rows = []
            while j < len(lines) and lines[j].startswith("|"):
                rows.append(lines[j])
                j += 1
            if any('<a id="p-' in r for r in rows):
                yield sec, sub, header, rows
            i = j
            continue
        i += 1


def robot_cell(row):
    cells = [c.strip() for c in row.strip()[1:-1].split(" | ")]
    return cells[1] if len(cells) > 1 else ""


def render(readme_text, robot, suffix):
    t = TEXT[suffix]
    groups = []  # [(sec, sub, header, rows)]
    for sec, sub, header, rows in parse(readme_text):
        mine = [r for r in rows if "`%s`" % robot in robot_cell(r)]
        if mine:
            groups.append((sec, sub, header, mine))
    n = sum(len(g[3]) for g in groups)

    langs = " | ".join(
        "<b>%s</b>" % name if s == suffix else '<a href="%s%s.md">%s</a>' % (robot, s, name)
        for _, s, name in EDITIONS)
    out = ["<!-- Generated by scripts/build_robot_pages.py from the README. Do not edit by hand. -->", "",
           '<p align="center">\n  %s\n</p>' % langs, "",
           "# %s · Awesome LimX" % robot, "",
           t["lead"].format(n=n, r=robot), ""]
    if OFFICIAL[robot]:
        links = " · ".join("[%s](https://github.com/limxdynamics/%s)" % (x, x) for x in OFFICIAL[robot])
        out += [t["official"].format(r=robot, links=links), ""]
    others = " · ".join("[%s](%s%s.md)" % (r, r, suffix) for r in ROBOTS if r != robot)
    out += ["[%s](../README%s.md) · %s: %s" % (t["back"], suffix, t["others"], others), ""]

    if not groups:
        out += [t["none"], ""]
    else:
        counts = {}
        for sec, _, _, rows in groups:
            counts[sec] = counts.get(sec, 0) + len(rows)
        out += ["## " + t["contents"], ""]
        out += ["- [%s](#%s) — %d" % (s, slug(s), c) for s, c in counts.items()]
        out += ["", "<sub>%s</sub>" % t["legend"], ""]
        last_sec = None
        for sec, sub, header, rows in groups:
            if sec != last_sec:
                out += ["## " + sec, ""]
                last_sec = sec
            if sub:
                out += ["### " + sub, ""]
            out += header + rows + [""]
    out += [t["submit"].format(r=robot), ""]
    return "\n".join(out)


def build(root):
    pages = {}
    for readme, suffix, _ in EDITIONS:
        path = os.path.join(root, readme)
        if not os.path.exists(path):
            continue
        text = open(path, encoding="utf-8").read()
        for robot in ROBOTS:
            pages[os.path.join(root, "robots", "%s%s.md" % (robot, suffix))] = render(text, robot, suffix)
    return pages


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="report stale pages instead of writing")
    ap.add_argument("--root", default=".")
    args = ap.parse_args()
    pages = build(args.root)
    stale = []
    for path, content in pages.items():
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != content:
            stale.append(path)
            if not args.check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                open(path, "w", encoding="utf-8").write(content)
    if args.check:
        for p in stale:
            print("out of date: %s (run python scripts/build_robot_pages.py)" % p)
        return 1 if stale else 0
    print("wrote %d of %d pages" % (len(stale), len(pages)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
